test('normalizeURL enforces HTTP(S) without credentials and appends /v1', () => {
  assert.equal(normalizeURL('http://127.0.0.1:20128'), 'http://127.0.0.1:20128/v1');
  assert.equal(normalizeURL('https://api.example.com/v1/'), 'https://api.example.com/v1');
  assert.throws(() => normalizeURL('http://remote.example.com/v1'), /Remote servers require HTTPS/);
  assert.throws(() => normalizeURL('https://user:pass@example.com/v1'), /without credentials/);
});

test('parseModels resolves context windows and sanitizes Gemini reasoning efforts', () => {
  const models = parseModels({
    data: [
      {
        id: 'agy/gemini-3.8-flash-tiered',
        name: 'Gemini 3.8 Flash',
        capabilities: { reasoning: true, effort_tiers: ['none', 'low', 'medium', 'high', 'xhigh', 'max'] }
      },
      {
        id: 'claude-sonnet-4-6',
        name: 'Claude Sonnet 4.6',
        capabilities: { reasoning: true }
      }
    ]
  });
  const gemini = models.find(m => m.id.includes('gemini'));
  assert.deepEqual(gemini.efforts, ['none', 'low', 'medium', 'high']);
  assert.equal(gemini.context, 1048576);

  const claude = models.find(m => m.id.includes('claude'));
  assert.equal(claude.context, 200000);
});

test('patchCodexTranslate and stripCodexTranslate preserve base ChatGPT/Codex model and sections', () => {
  const original = [
    'model = "gpt-6.1-sol"',
    'model_reasoning_effort = "high"',
    'approval_policy = "never"',
    '[desktop]',
    'conversationDetailMode = "STEPS_PROSE"',
    '[mcp_servers.node_repl.env]',
    'SKY_CUA_NATIVE_PIPE_DIRECTORY = "\\\\.\\pipe\\codex-123"'
  ].join('\n');

  const generated = translateBridgeConfig('http://127.0.0.1:24131/v1');
  const patched = patchCodexTranslate(original, generated, false);

  // Base model and reasoning effort must remain untouched
  assert.match(patched, /^model = "gpt-6\.1-sol"$/m);
  assert.match(patched, /^model_reasoning_effort = "high"$/m);
  // No omniroute_bridge provider or catalog override may be injected
  assert.doesNotMatch(patched, /omniroute_bridge/);
  assert.doesNotMatch(patched, /model_catalog_json/);
  // Only openai_base_url is added
  assert.match(patched, /^openai_base_url = "http:\/\/127\.0\.0\.1:24131\/v1"$/m);
  assert.match(patched, /\[desktop\]/);

  const stripped = stripCodexTranslate(patched, original);
  assert.doesNotMatch(stripped, /openai_base_url/);
  assert.doesNotMatch(stripped, /# Generated by codex-translate/);
  assert.match(stripped, /^model = "gpt-6\.1-sol"$/m);
  assert.match(stripped, /SKY_CUA_NATIVE_PIPE_DIRECTORY/);
});

test('cross-platform path resolution and AES-256-GCM credential store work on Linux and macOS', () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'codex-translate-posix-'));
  try {
    const fakeHome = path.join(tmp, 'home', 'dev');
    const xdgData = path.join(fakeHome, '.local', 'share-custom');
    const macAppSupport = path.join(fakeHome, 'Library', 'Application Support');
    fs.mkdirSync(xdgData, { recursive: true });
    fs.mkdirSync(macAppSupport, { recursive: true });

    // Linux defaultDataDir (with and without XDG_DATA_HOME)
    const linuxDirDefault = defaultDataDir('codex-translate', 'linux', { HOME: fakeHome });
    assert.ok(linuxDirDefault.endsWith(path.join('.local', 'share', 'OmniRouteIntegrations', 'codex-translate')));
    const linuxDirXdg = defaultDataDir('codex-translate', 'linux', { HOME: fakeHome, XDG_DATA_HOME: xdgData });
    assert.equal(linuxDirXdg, path.join(xdgData, 'OmniRouteIntegrations', 'codex-translate'));

    // macOS defaultDataDir (Library/Application Support)
    const macDir = defaultDataDir('codex-translate', 'darwin', { HOME: fakeHome });
    assert.equal(macDir, path.join(macAppSupport, 'OmniRouteIntegrations', 'codex-translate'));

    // defaultCodexHome on Linux and macOS
    assert.equal(defaultCodexHome('linux', { HOME: fakeHome }), path.join(fakeHome, '.codex'));
    assert.equal(defaultCodexHome('darwin', { HOME: fakeHome, CODEX_HOME: '/custom/codex' }), '/custom/codex');

    // resolveCodexExe on Linux and macOS
    const binDir = path.join(fakeHome, '.local', 'bin');
    fs.mkdirSync(binDir, { recursive: true });
    const fakeCodexBin = path.join(binDir, 'codex');
    fs.writeFileSync(fakeCodexBin, '#!/bin/sh\n');
    assert.equal(resolveCodexExe(path.join(fakeHome, '.codex'), 'linux', { HOME: fakeHome, PATH: '' }), fakeCodexBin);
    assert.equal(resolveCodexExe(path.join(fakeHome, '.codex'), 'darwin', { HOME: fakeHome, PATH: binDir }), fakeCodexBin);

    // POSIX AES-256-GCM credential Protect & Read round-trip on Linux and macOS
    for (const platform of ['linux', 'darwin']) {
      const credFile = path.join(tmp, `cred-${platform}`, 'provider-1.dpapi');
      credential('', 'Protect', credFile, `secret-key-${platform}-42`, { platform });
      const rawDisk = fs.readFileSync(credFile, 'utf8');
      assert.match(rawDisk, /^ct-aes256gcm:v1:/);
      assert.doesNotMatch(rawDisk, /secret-key-/);
      const decrypted = credential('', 'Read', credFile, undefined, { platform });
      assert.equal(decrypted, `secret-key-${platform}-42`);

      // Tampering with ciphertext must fail authentication
      fs.writeFileSync(credFile, rawDisk.slice(0, -4) + 'ffff\n');
      assert.throws(() => credential('', 'Read', credFile, undefined, { platform }), /Credential helper failed/);
    }
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
});
